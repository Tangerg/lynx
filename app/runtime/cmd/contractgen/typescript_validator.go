package main

import (
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"
)

// The TypeScript validator is COMPILED FROM THE SCHEMA TREE, for the same reason
// the TypeScript types are: two independent walks of the Go types would be two
// authors of one rule, and contract §11.4 gate 6 asks that the three statements of
// a constraint agree. Deriving one from the other makes agreement structural —
// there is no path by which the schema states `minLength` and the validator forgets
// it.
//
// It is the client's half of §11.3's "authoritative/terminal runtime validators",
// and its scope follows from which side owns which frames. The runtime RECEIVES
// requests, and Go's typed decode already fixes their structure, so the generated
// Go validator only adds what typing cannot say (value constraints, enum
// membership). A client RECEIVES results and events with no typing left at runtime
// at all, so this one carries the whole tree: type keywords, required, enum,
// minLength / minimum, union exclusivity, presence rules.
//
// Nothing here decides what a keyword means; `wireCheck.ts` does, once. This file
// only states which keyword applies where — the same division as the generated Go
// validator and its hand-written `required` / `positive` helpers.

// tsValidatorFileName is the second generated module in the frontend's tree.
const tsValidatorFileName = "wire.validate.generated.ts"

type checkEmitter struct {
	set *schemaSet

	// used records the primitives the body actually calls, so the import list names
	// exactly those — the frontend compiles with noUnusedLocals.
	used map[string]bool
}

func newWireChecks(set *schemaSet) string {
	emitter := &checkEmitter{set: set, used: make(map[string]bool)}
	names := slices.Sorted(maps.Keys(set.defs))

	// The body is rendered first: it is what decides the import list.
	var body strings.Builder
	body.WriteString("const CHECKS: Record<WireTypeName, WireCheck> = {\n")
	for _, name := range names {
		fmt.Fprintf(&body, "  %s: %s,\n", name, shift(emitter.compile(set.defs[name]), 1))
	}
	body.WriteString("};\n")

	var out strings.Builder
	out.WriteString(checksHeader)
	fmt.Fprintf(&out, "import { %s } from \"./wireCheck\";\n", strings.Join(slices.Sorted(maps.Keys(emitter.used)), ", "))
	out.WriteString("import type { WireCheck, WireViolation } from \"./wireCheck\";\n\n")
	out.WriteString("/** Every shape the protocol publishes. */\nexport type WireTypeName =\n")
	for _, name := range names {
		fmt.Fprintf(&out, "  | %s\n", strconv.Quote(name))
	}
	out.WriteString("  ;\n\n")
	out.WriteString(body.String())
	out.WriteString(checksEntryPoint)
	return out.String()
}

const checksHeader = `// Code generated by cmd/contractgen. DO NOT EDIT.
//
// The runtime checks of the Lyra Runtime Protocol, compiled from the same schema
// tree that produces contract/schema.json — so a rule the published schema states
// is a rule this file enforces, structurally rather than by remembering to.
//
// What each call MEANS lives in wireCheck.ts. This file only says which rule
// applies where.

`

const checksEntryPoint = `
/**
 * validateWire reports every way a value fails the published shape, and an empty
 * list when it satisfies it.
 *
 * Paths are rooted at the type's own name, so a report reads
 * ` + "`RunEvent.event.outcome.type`" + `.
 */
export function validateWire(type: WireTypeName, value: unknown): WireViolation[] {
  const out: WireViolation[] = [];
  CHECKS[type](value, type, out);
  return out;
}
`

// compile renders one schema node as a check expression, rendered as if it began at
// column zero — a container re-indents what it embeds.
func (e *checkEmitter) compile(node *schema) string {
	if len(node.AnyOf) > 0 {
		// Nothing emits anyOf today. Translating it wrong is worse than not compiling:
		// a rule the schema publishes would go unchecked with nobody the wiser.
		panic("contractgen: the wire check compiler has no translation for anyOf")
	}
	if node.Ref != "" {
		name, _ := strings.CutPrefix(node.Ref, refPrefix)
		return e.call("ref", "() => CHECKS."+name)
	}

	// A node is the conjunction of its keywords, so each keyword contributes one
	// check and more than one is an allOf. The value set of an `enum` is the
	// exception, because it implies the `type: string` beside it and never appears
	// without one — whereas a value constraint appears BOTH beside a type keyword and
	// alone in the branch that narrows a field of a shared shape, so it stays its own
	// call and one rule has one spelling.
	var parts []string
	switch {
	case node.Const != "":
		parts = append(parts, e.call("literal", strconv.Quote(node.Const)))
	case len(node.Enum) > 0:
		parts = append(parts, e.call("enumOf", "["+strings.Join(quoteAll(node.Enum), ", ")+"]"))
	default:
		if part := e.value(node); part != "" {
			parts = append(parts, part)
		}
	}
	if node.MinLength != nil {
		parts = append(parts, e.call("minLength", strconv.Itoa(*node.MinLength)))
	}
	if node.Minimum != nil {
		parts = append(parts, e.call("minimum", strconv.FormatInt(*node.Minimum, 10)))
	}
	if len(node.OneOf) > 0 {
		parts = append(parts, e.call("oneOf", e.list(node.OneOf)))
	}
	for _, member := range node.AllOf {
		parts = append(parts, e.compile(member))
	}
	if node.If != nil {
		// Both halves of a presence rule are objects in their own right, so they get a
		// line each rather than running together inside one argument list.
		parts = append(parts, e.callBlock("ifThen", e.compile(node.If), e.compile(node.Then)))
	}

	switch len(parts) {
	case 0:
		return e.call("anything")
	case 1:
		return parts[0]
	default:
		return e.call("allOf", block(parts))
	}
}

// value renders the `type` keyword and the constraints that ride on it.
func (e *checkEmitter) value(node *schema) string {
	keyword, _ := node.Type.(string)
	switch keyword {
	case "object":
		if node.AdditionalProps != nil {
			child, ok := node.AdditionalProps.(*schema)
			if !ok {
				panic(fmt.Sprintf("contractgen: additionalProperties is %T, which the check compiler cannot read", node.AdditionalProps))
			}
			return e.call("record", e.compile(child))
		}
		return e.call("object", e.properties(node), values(node.Required))
	case "array":
		return e.call("array", e.compile(node.Items))
	case "string":
		return e.call("text")
	case "integer":
		return e.call("integer")
	case "number":
		return e.call("numeric")
	case "boolean":
		return e.call("flag")
	case "":
		// A union branch and a presence rule state fields with no type keyword: the
		// definition they sit inside already asserted the object.
		if len(node.Properties) > 0 || len(node.Required) > 0 {
			return e.call("fields", e.properties(node), values(node.Required))
		}
		return ""
	default:
		panic("contractgen: the wire check compiler has no translation for JSON type " + keyword)
	}
}

func (e *checkEmitter) properties(node *schema) string {
	names := slices.Sorted(maps.Keys(node.Properties))
	if len(names) == 0 {
		return "{}"
	}
	var out strings.Builder
	out.WriteString("{\n")
	for _, name := range names {
		fmt.Fprintf(&out, "  %s: %s,\n", propertyKey(name), shift(e.property(node.Properties[name]), 1))
	}
	out.WriteString("}")
	return out.String()
}

func (e *checkEmitter) property(node any) string {
	switch typed := node.(type) {
	case *schema:
		return e.compile(typed)
	case bool:
		if typed {
			return e.call("anything")
		}
		return e.call("absent")
	default:
		panic(fmt.Sprintf("contractgen: a property is %T, which is neither a schema nor a boolean schema", node))
	}
}

// list renders sibling schemas one per line, which keeps a union's diff readable:
// adding a variant touches one line.
func (e *checkEmitter) list(nodes []*schema) string {
	rendered := make([]string, 0, len(nodes))
	for _, node := range nodes {
		rendered = append(rendered, e.compile(node))
	}
	return block(rendered)
}

func (e *checkEmitter) call(name string, arguments ...string) string {
	e.used[name] = true
	return name + "(" + strings.Join(arguments, ", ") + ")"
}

// callBlock renders a call with one argument per line.
func (e *checkEmitter) callBlock(name string, arguments ...string) string {
	e.used[name] = true
	var out strings.Builder
	out.WriteString(name + "(\n")
	for _, argument := range arguments {
		fmt.Fprintf(&out, "  %s,\n", shift(argument, 1))
	}
	out.WriteString(")")
	return out.String()
}

// block renders sibling checks one per line, so adding a variant or a constraint
// touches one line of the diff — unless every sibling is a leaf, in which case a
// line each is noise and they go inline.
func block(items []string) string {
	if !slices.ContainsFunc(items, func(item string) bool { return strings.Contains(item, "\n") }) {
		return "[" + strings.Join(items, ", ") + "]"
	}
	var out strings.Builder
	out.WriteString("[\n")
	for _, item := range items {
		fmt.Fprintf(&out, "  %s,\n", shift(item, 1))
	}
	out.WriteString("]")
	return out.String()
}

func values(items []string) string {
	return "[" + strings.Join(quoteAll(items), ", ") + "]"
}

// shift re-indents an already-rendered expression for the depth it is embedded at.
// Every expression is rendered as if it started at column zero, so a container only
// has to say how deep it is putting things.
func shift(rendered string, levels int) string {
	return strings.ReplaceAll(rendered, "\n", "\n"+strings.Repeat("  ", levels))
}
