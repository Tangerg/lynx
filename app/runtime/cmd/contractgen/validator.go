// The authoritative Go wire validator: the Go half of contract §11.3's
// "authoritative/terminal runtime validators".
//
// It replaces hand-written request checks and also guards typed output boundaries.
// Generating Go, schema and TypeScript checks from the same registry is what makes
// §11.4 gate 6's three-way equivalence structural rather than aspirational.
//
// Four rule sources, and none restates another's job:
//
//   - the declared value constraints (a string that may not be empty, a number
//     that may not be zero) — reflection cannot see these;
//   - closed-enum membership, DERIVED from the enum's own declared value set. Go's
//     decoder puts any string into a named string type, so without this check a
//     bogus tag reaches a use case or client;
//   - registered union variants;
//   - registered conditional presence rules.

// validatorFile is written into the protocol package, beside the shapes it checks.
const validatorFile = "wire_constraints.generated.go"

func newValidators(registry *operation.Registry, shapes *dispatch.Shapes) string {
	var out strings.Builder
	out.WriteString("// Code generated by cmd/contractgen. DO NOT EDIT.\n\n")
	out.WriteString("package protocol\n")

	declared := make(map[reflect.Type][]dispatch.FieldConstraint)
	for _, spec := range shapes.ValueConstraints() {
		declared[spec.GoType] = append(declared[spec.GoType], spec.Constraints...)
	}
	unions := make(map[reflect.Type]dispatch.UnionSpec)
	for _, spec := range shapes.Unions() {
		unions[spec.GoType] = spec
	}
	objects := make(map[reflect.Type][]dispatch.PresenceRule)
	for _, spec := range shapes.Constraints() {
		objects[spec.GoType] = append(objects[spec.GoType], spec.Rules...)
	}

	// Request roots come first in method-registration order. Registered unions,
	// conditional objects and value-constrained roots follow in declaration order.
	// This makes every Registry-authored shape rule reachable by the Go generator,
	// including DTOs that only travel from server to client.
	var targets []reflect.Type
	written := make(map[reflect.Type]bool)
	for _, meta := range registry.Metas() {
		if meta.Params == nil || written[meta.Params] || meta.Params.Name() == "" {
			continue
		}
		written[meta.Params] = true
		targets = append(targets, meta.Params)
	}
	for _, spec := range shapes.Unions() {
		if written[spec.GoType] || spec.GoType.Name() == "" {
			continue
		}
		written[spec.GoType] = true
		targets = append(targets, spec.GoType)
	}
	for _, spec := range shapes.Constraints() {
		if written[spec.GoType] || spec.GoType.Name() == "" {
			continue
		}
		written[spec.GoType] = true
		targets = append(targets, spec.GoType)
	}
	for _, spec := range shapes.ValueConstraints() {
		if written[spec.GoType] || spec.GoType.Name() == "" {
			continue
		}
		written[spec.GoType] = true
		targets = append(targets, spec.GoType)
	}

	for _, target := range targets {
		checks := validatorChecks(target, declared[target], unions[target], objects[target])
		if len(checks) == 0 {
			continue
		}
		fmt.Fprintf(&out, "\nfunc (%s %s) ValidateWire() error {\n", receiverName(target), target.Name())
		fmt.Fprintf(&out, "\treturn collectWireViolations(%q,\n", target.Name())
		for _, check := range checks {
			fmt.Fprintf(&out, "\t\t%s,\n", check)
		}
		out.WriteString("\t)\n}\n")
	}
	return out.String()
}

// receiverName is the identifier the generated method binds its receiver to.
// Generated methods follow the same rule as hand-written ones — the lowercased
// first letter of the type — so a shape does not answer to two different names
// depending on which half of the file a reader is in.
func receiverName(shape reflect.Type) string {
	if shape.Name() == "" {
		panic("contractgen: cannot name a receiver for an unnamed shape")
	}
	return strings.ToLower(shape.Name()[:1])
}

// validatorChecks builds every frame-local check registered for one wire shape.
func validatorChecks(
	shape reflect.Type,
	constraints []dispatch.FieldConstraint,
	union dispatch.UnionSpec,
	rules []dispatch.PresenceRule,
) []string {
	recv := receiverName(shape)
	checks := make([]string, 0, len(constraints))
	for _, constraint := range constraints {
		if check := constraintCheck(shape, constraint, union); check != "" {
			checks = append(checks, check)
		}
	}
	checks = append(checks, enumChecks(shape)...)
	checks = append(checks, unionChecks(union, recv)...)
	checks = append(checks, objectChecks(rules, recv)...)
	return checks
}

func constraintCheck(
	shape reflect.Type,
	constraint dispatch.FieldConstraint,
	union dispatch.UnionSpec,
) string {
	selector, leaf, found := contractshape.GoPath(shape, constraint.Field)
	if !found {
		panic(fmt.Sprintf("contractgen: %s has no field %q", shape.Name(), constraint.Field))
	}
	field := strconv.Quote(constraint.Field)
	ref := receiverName(shape) + "." + selector
	switch constraint.Kind {
	case dispatch.ConstraintNonEmpty:
		// A non-pointer scalar cannot distinguish an omitted JSON property from its
		// zero value after decoding. When a union branch owns the property's
		// requiredness, requiredWhen below already rejects that zero value in the
		// branch where it is required and accepts it where the property is forbidden.
		// An unconditional requiredText would reject every other legal branch.
		if leaf.Optional && leaf.Type.Kind() != reflect.Pointer && unionRequiresField(union, constraint.Field) {
			return ""
		}
		validatorName := "requiredText"
		if leaf.Optional && leaf.Type.Kind() == reflect.Pointer {
			validatorName = "optionalText"
		}
		return fmt.Sprintf("%s(%s, %s)", validatorName, field, stringExpr(shape, selector, leaf.Type))
	case dispatch.ConstraintPositive:
		validatorName := "positiveNumber"
		if leaf.Type.Kind() == reflect.Pointer {
			validatorName = "optionalPositiveNumber"
		} else if leaf.Optional {
			validatorName = "optionalPositiveScalarNumber"
		}
		return fmt.Sprintf("%s(%s, %s)", validatorName, field, ref)
	case dispatch.ConstraintNonNegative:
		validatorName := "nonNegativeNumber"
		if leaf.Type.Kind() == reflect.Pointer {
			validatorName = "optionalNonNegativeNumber"
		}
		return fmt.Sprintf("%s(%s, %s)", validatorName, field, ref)
	case dispatch.ConstraintNonEmptyItems:
		validatorName := "requiredItems"
		if leaf.Optional {
			validatorName = "nonEmptyItems"
		}
		return fmt.Sprintf("%s(%s, %s)", validatorName, field, ref)
	case dispatch.ConstraintNonEmptyProperties:
		return fmt.Sprintf("nonEmptyProperties(%s, %s)", field, ref)
	case dispatch.ConstraintUniqueItems:
		validatorName := "uniqueItems"
		if leaf.Type.Kind() == reflect.Pointer {
			validatorName = "optionalUniqueItems"
		}
		return fmt.Sprintf("%s(%s, %s)", validatorName, field, ref)
	case dispatch.ConstraintMinItems:
		validatorName := "requiredMinItems"
		if leaf.Optional {
			validatorName = "optionalMinItems"
		}
		return fmt.Sprintf("%s(%s, %s, %d)", validatorName, field, ref, constraint.Limit)
	case dispatch.ConstraintMaxLength:
		validatorName := "maxLength"
		if leaf.Type.Kind() == reflect.Pointer {
			validatorName = "optionalMaxLength"
		}
		return fmt.Sprintf(
			"%s(%s, %s, %d)",
			validatorName,
			field,
			stringExpr(shape, selector, leaf.Type),
			constraint.Limit,
		)
	case dispatch.ConstraintMinimum:
		validatorName := "minimumNumber"
		if leaf.Type.Kind() == reflect.Pointer {
			validatorName = "optionalMinimumNumber"
		}
		return fmt.Sprintf("%s(%s, %s, %d)", validatorName, field, ref, constraint.Limit)
	case dispatch.ConstraintMaximum:
		validatorName := "maximumNumber"
		if leaf.Type.Kind() == reflect.Pointer {
			validatorName = "optionalMaximumNumber"
		}
		return fmt.Sprintf("%s(%s, %s, %d)", validatorName, field, ref, constraint.Limit)
	default:
		panic(fmt.Sprintf(
			"contractgen: %s.%s uses unsupported constraint %s",
			shape.Name(),
			constraint.Field,
			constraint.Kind,
		))
	}
}

func unionRequiresField(union dispatch.UnionSpec, field string) bool {
	if union.GoType == nil {
		return false
	}
	for _, variant := range union.Variants {
		if slices.Contains(variant.Required, field) {
			return true
		}
	}
	if pattern := union.PatternVariant; pattern != nil {
		return slices.Contains(pattern.Required, field)
	}
	return false
}

func enumChecks(shape reflect.Type) []string {
	recv := receiverName(shape)
	var checks []string
	for _, field := range contractshape.Fields(shape) {
		if values, found := contractcatalog.EnumValues(field.Type); found {
			checks = append(checks, fmt.Sprintf("closedEnum(%s, string(%s.%s), %s, %t)",
				strconv.Quote(field.Name), recv, field.GoName, valueList(values), field.Optional))
			continue
		}
		if field.Type.Kind() == reflect.Slice {
			if values, found := contractcatalog.EnumValues(field.Type.Elem()); found {
				checks = append(checks, fmt.Sprintf("closedEnumItems(%s, %s.%s, %s)",
					strconv.Quote(field.Name), recv, field.GoName, valueList(values)))
			}
		}
	}
	return checks
}

func unionChecks(union dispatch.UnionSpec, recv string) []string {
	if union.GoType == nil {
		return nil
	}
	paths := unionPaths(union)
	var checks []string
	if pattern := union.PatternVariant; pattern != nil {
		field, ok := contractshape.LookupField(union.GoType, union.Discriminator)
		if !ok {
			panic(fmt.Sprintf("contractgen: %s has no discriminator %q", union.GoType.Name(), union.Discriminator))
		}
		tags := make([]string, 0, len(union.Variants))
		for _, variant := range union.Variants {
			tags = append(tags, variant.Tag)
		}
		checks = append(checks, fmt.Sprintf(
			"unionTag(%q, string(%s.%s), %s, %q)",
			union.Discriminator, recv, field.GoName, valueList(tags), pattern.TagPattern,
		))
	}
	for _, variant := range union.Variants {
		applies := fmt.Sprintf("wireFieldEquals(%s, %q, %q)", recv, union.Discriminator, variant.Tag)
		allowed := append(slices.Clone(variant.Required), variant.Optional...)
		for _, field := range variant.Required {
			checks = append(checks, fmt.Sprintf("requiredWhen(%s, %q, %s)", applies, field, recv))
		}
		for _, field := range paths {
			if slices.Contains(allowed, field) {
				continue
			}
			checks = append(checks, fmt.Sprintf("forbiddenWhen(%s, %q, %s)", applies, field, recv))
		}
	}
	if pattern := union.PatternVariant; pattern != nil {
		applies := fmt.Sprintf("wireFieldMatches(%s, %q, %q)", recv, union.Discriminator, pattern.TagPattern)
		allowed := append(slices.Clone(pattern.Required), pattern.Optional...)
		for _, field := range pattern.Required {
			checks = append(checks, fmt.Sprintf("requiredWhen(%s, %q, %s)", applies, field, recv))
		}
		for _, field := range paths {
			if slices.Contains(allowed, field) {
				continue
			}
			checks = append(checks, fmt.Sprintf("forbiddenWhen(%s, %q, %s)", applies, field, recv))
		}
	}
	return checks
}

func unionPaths(union dispatch.UnionSpec) []string {
	var paths []string
	for _, variant := range union.Variants {
		for _, field := range append(slices.Clone(variant.Required), variant.Optional...) {
			if field != union.Discriminator && !slices.Contains(paths, field) {
				paths = append(paths, field)
			}
		}
	}
	if pattern := union.PatternVariant; pattern != nil {
		for _, field := range append(slices.Clone(pattern.Required), pattern.Optional...) {
			if field != union.Discriminator && !slices.Contains(paths, field) {
				paths = append(paths, field)
			}
		}
	}
	return paths
}

func objectChecks(rules []dispatch.PresenceRule, recv string) []string {
	var checks []string
	for _, rule := range rules {
		applies := conditionExpression(rule.When, recv)
		for _, field := range rule.Required {
			checks = append(checks, fmt.Sprintf("requiredWhen(%s, %q, %s)", applies, field, recv))
		}
		for _, field := range rule.Forbidden {
			checks = append(checks, fmt.Sprintf("forbiddenWhen(%s, %q, %s)", applies, field, recv))
		}
	}
	return checks
}

func conditionExpression(conditions []operation.FieldCondition, recv string) string {
	if len(conditions) == 0 {
		return "true"
	}
	parts := make([]string, 0, len(conditions))
	for _, condition := range conditions {
		switch condition.Operator.String() {
		case "equals":
			parts = append(parts, fmt.Sprintf(
				"wireFieldEquals(%s, %q, %q)", recv, condition.Field, condition.Value,
			))
		case "present":
			parts = append(parts, fmt.Sprintf("wireFieldPresent(%s, %q)", recv, condition.Field))
		default:
			panic(fmt.Sprintf("contractgen: unsupported presence operator %q", condition.Operator))
		}
	}
	return strings.Join(parts, " && ")
}

// stringExpr reads a field as a string. A named string type — a closed enum, an id —
// needs the conversion, and a plain string must not have one: an identity conversion
// is what the linter deletes, so emitting one everywhere would make the generated
// file fail the check it is generated to pass.
func stringExpr(shape reflect.Type, selector string, leaf reflect.Type) string {
	const builtinStringTypeName = "string"

	ref := receiverName(shape) + "." + selector
	if leaf.Kind() == reflect.Pointer {
		return ref
	}
	if leaf.Kind() == reflect.String && leaf.Name() != builtinStringTypeName {
		return fmt.Sprintf("string(%s)", ref)
	}
	return ref
}

func valueList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, strconv.Quote(value))
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// valueConstraintsFor returns the declared constraints on one field of a shape,
// so the schema walk can state the same rule with its corresponding keyword.
func (s *schemaSet) valueConstraintsFor(owner reflect.Type, field string) []dispatch.FieldConstraint {
	var out []dispatch.FieldConstraint
	owners := append([]reflect.Type{owner}, contractshape.Embeds(owner)...)
	for _, candidate := range owners {
		for _, constraint := range s.values[candidate] {
			if constraint.Field == field && !slices.Contains(out, constraint) {
				out = append(out, constraint)
			}
		}
	}
	return out
}
